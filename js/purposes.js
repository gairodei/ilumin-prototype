/* ---------- Lookup ---------- */
const IDX_NAV = /^(goTok|aJump|agyGo|cooGo|cooIdxGo|wpcGo)$/;
// What the link opens: the route token for navigation links, otherwise the action and its settings (IDs left out)
function idxTarget(b) {
  const d = b.dataset, a = d.act || '';
  if (d.go) return d.go + (d.id ? '.' + d.id : '');
  if (IDX_NAV.test(a)) return d.t || d.r || '';
  return a + ':' + Object.keys(d).filter(k => !['act', 'id', 'no'].includes(k)).sort().map(k => k + '=' + d[k]).join(',');
}
// Keys for an entry whose target carries live data, read from the item it opens
function idxTypeKeys(b) {
  const t = idxTarget(b), [r, id, tab] = t.split('.'), d = b.dataset, out = [];
  try {
    if (r === 'a-queue' && id && typeof qItem === 'function') { const i = qItem(id); if (i) out.push('queue:' + i.type); }
    if (r === 't-mark' && id) { const s = typeof tasSubs === 'function' ? (tasSubs() || []).find(x => x.key === id) : null; out.push(STORE.tas && id === STORE.tas.limitKey ? 'mark:limit' : s && s.resub ? 'mark:resub' : 'mark:first'); }
    if (r === 'c-release' && id) out.push('release:item');
    if (/^g-(learner|bundle|purchase)$/.test(r) && id) out.push('agency:' + r.slice(2));
    if (r === 'q-record' && id && STORE.iqa) {
      const rec = (STORE.iqa.recs || []).find(x => x.id === id), gone = rec && (ADMIN.staff || []).some(st => st.name === rec.assessor && st.status === 'Deactivated');
      if (rec && rec.archived) out.push('record:archived');
      if (rec && rec.discontinued) out.push('record:discontinued');
      if (gone) out.push('record:former');
    }
    if (r === 'c-batches' && id) out.push('batch:detail');
    if (/^w-(permission|visit|info|withdraw)$/.test(r) && typeof wLink === 'function') {
      const l = wLink(id), st = l ? wState(l) : 'invalid', k = r.slice(2);
      if (k === 'info' && l) out.push('wpc:info:' + l.info);
      // a visit cancelled after the contact accepted it: the cancellation is what the page shows
      if (k === 'visit' && l && typeof wObs === 'function' && (wObs(l) || {}).status === 'Cancelled') out.push('wpc:visit:cancelled');
      out.push(`wpc:${k}:${st}${st === 'used' && l && l.used ? ':' + l.used.decision : ''}${tab ? ':' + tab : ''}`, 'wpc:' + k);
    }
    if (r === 'w-inbox' && id && STORE.wpc) { const e = STORE.wpc.emails.find(x => x.id === id); if (e) out.push('wpc:email:' + e.kind); }
    if (d.act === 'vOpen' && typeof verSamples === 'function') { const s = verSamples().find(x => x[0] === d.no); if (s) out.push('cert:' + s[1]); }
  } catch (e) { /* item not found: fall through */ }
  return out;
}
// Last resort (marked, so the test shows none are used)
function idxFallback(b) {
  const a = b.dataset.act || '';
  if (/^demoSignInAs|^switchRole$/.test(a)) return 'Opens that portal as this demo account.';
  if (b.dataset.m) return 'Opens this dialog where it normally appears.';
  if (b.dataset.e) return 'Shows the portal in this state.';
  return 'Opens this screen.';
}
// → [purpose, how it was found: 'entry' | the type key | 'route' | 'fallback']
function idxPurpose(key, b, section, n) {
  const own = IDX_P[key] || {}, t = idxTarget(b), sk = section + '|' + t;
  if (own[sk + '#' + n]) return [own[sk + '#' + n], 'entry'];
  for (const k of idxTypeKeys(b)) { if (IDX_TYPE_P[section + '|' + k]) return [IDX_TYPE_P[section + '|' + k], k]; if (IDX_TYPE_P[k]) return [IDX_TYPE_P[k], k]; }
  if (own[sk + '#1']) return [own[sk + '#1'], 'entry'];
  if (ROUTE_PURPOSE[t]) return [ROUTE_PURPOSE[t], 'route'];
  return [idxFallback(b), 'fallback'];
}
function withPurposes(key, h) {
  const t = document.createElement('template'); t.innerHTML = h;
  t.content.querySelectorAll('.idx-sec').forEach(sec => {
    const section = ((sec.querySelector('h2') || {}).textContent || '').trim(), count = {};
    sec.querySelectorAll('.idx-list > li').forEach(li => {
      const b = li.querySelector(':scope > button, :scope > a'); if (!b || li.querySelector('.idx-purpose')) return;
      const tail = [...li.childNodes].slice([...li.childNodes].indexOf(b) + 1).map(n => n.textContent).join('').trim();
      if (/^·\s*.{4,}/.test(tail)) return; // already says what it is
      const tg = idxTarget(b); count[tg] = (count[tg] || 0) + 1;
      const [txt, how] = idxPurpose(key, b, section, count[tg]);
      li.insertAdjacentHTML('beforeend', `<span class="idx-purpose xs muted" data-pk="${esc(how)}"${how === 'fallback' ? ' data-pf="fallback"' : ''}>${esc(txt)}</span>`);
    });
  });
  const box = document.createElement('div'); box.appendChild(t.content.cloneNode(true)); return box.innerHTML;
}
// Wrap every index once, at the end of loading
IDX_ROUTES.forEach(k => { const f = SCREENS[k]; if (f) SCREENS[k] = p => withPurposes(k, f(p)); });
